PRAGMA foreign_keys = ON;

DROP TABLE IF EXISTS HISTORICO;
DROP TABLE IF EXISTS UTILIZACAO_EQUIPAMENTO;
DROP TABLE IF EXISTS PAGAMENTO;
DROP TABLE IF EXISTS CONTRATO;
DROP TABLE IF EXISTS RELATORIO;
DROP TABLE IF EXISTS EVIDENCIA_LOCAL;
DROP TABLE IF EXISTS LOCAL;
DROP TABLE IF EXISTS EVIDENCIA_PESSOA;
DROP TABLE IF EXISTS EVIDENCIA;
DROP TABLE IF EXISTS ENTREVISTA_DETETIVE;
DROP TABLE IF EXISTS ENTREVISTA;
DROP TABLE IF EXISTS ENVOLVIMENTO;
DROP TABLE IF EXISTS PESSOA;
DROP TABLE IF EXISTS MISSAO_DETETIVE;
DROP TABLE IF EXISTS MISSAO;
DROP TABLE IF EXISTS ATRIBUICAO;
DROP TABLE IF EXISTS INVESTIGACAO;
DROP TABLE IF EXISTS EQUIPAMENTO;
DROP TABLE IF EXISTS DETETIVE_ESPECIALIDADE;
DROP TABLE IF EXISTS ESPECIALIDADE;
DROP TABLE IF EXISTS DETETIVE;
DROP TABLE IF EXISTS CLIENTE;

CREATE TABLE CLIENTE (
    id_cliente INTEGER PRIMARY KEY AUTOINCREMENT,
    nome TEXT NOT NULL,
    tipo_cliente TEXT NOT NULL CHECK (tipo_cliente IN ('PF', 'PJ')),
    cpf_cnpj TEXT NOT NULL UNIQUE,
    telefone TEXT NOT NULL,
    email TEXT UNIQUE,
    endereco TEXT NOT NULL
);

CREATE TABLE DETETIVE (
    id_detetive INTEGER PRIMARY KEY AUTOINCREMENT,
    nome TEXT NOT NULL,
    cpf TEXT NOT NULL UNIQUE,
    telefone TEXT NOT NULL,
    email TEXT UNIQUE,
    status_ativo INTEGER NOT NULL DEFAULT 1 CHECK (status_ativo IN (0, 1))
);

CREATE TABLE ESPECIALIDADE (
    id_especialidade INTEGER PRIMARY KEY AUTOINCREMENT,
    nome_especialidade TEXT NOT NULL UNIQUE,
    descricao TEXT
);

CREATE TABLE DETETIVE_ESPECIALIDADE (
    id_detetive INTEGER NOT NULL,
    id_especialidade INTEGER NOT NULL,
    PRIMARY KEY (id_detetive, id_especialidade),
    FOREIGN KEY (id_detetive) REFERENCES DETETIVE(id_detetive) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (id_especialidade) REFERENCES ESPECIALIDADE(id_especialidade) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE EQUIPAMENTO (
    id_equipamento INTEGER PRIMARY KEY AUTOINCREMENT,
    nome TEXT NOT NULL,
    numero_serie TEXT NOT NULL UNIQUE,
    estado_conservacao TEXT NOT NULL DEFAULT 'OPERACIONAL' CHECK (estado_conservacao IN ('OPERACIONAL', 'DEFEITUOSO'))
);

CREATE TABLE INVESTIGACAO (
    id_investigacao INTEGER PRIMARY KEY AUTOINCREMENT,
    id_cliente INTEGER NOT NULL,
    id_detetive_responsavel INTEGER NOT NULL,
    titulo TEXT NOT NULL,
    descricao TEXT NOT NULL,
    data_abertura TEXT NOT NULL DEFAULT (DATE('now')),
    data_encerramento TEXT,
    status TEXT NOT NULL DEFAULT 'ABERTA' CHECK (status IN ('ABERTA', 'EM_ANDAMENTO', 'SUSPENSA', 'ENCERRADA', 'CANCELADA')),
    nivel_confidencialidade TEXT NOT NULL DEFAULT 'RESTRITO' CHECK (nivel_confidencialidade IN ('PUBLICO', 'RESTRITO', 'CONFIDENCIAL', 'SECRETO')),
    FOREIGN KEY (id_cliente) REFERENCES CLIENTE(id_cliente) ON DELETE RESTRICT ON UPDATE CASCADE,
    FOREIGN KEY (id_detetive_responsavel) REFERENCES DETETIVE(id_detetive) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_datas_investigacao CHECK (data_encerramento IS NULL OR data_encerramento >= data_abertura)
);

CREATE TABLE ATRIBUICAO (
    id_atribuicao INTEGER PRIMARY KEY AUTOINCREMENT,
    id_investigacao INTEGER NOT NULL,
    id_detetive INTEGER NOT NULL,
    data_inicio TEXT NOT NULL DEFAULT (DATE('now')),
    data_fim TEXT,
    eh_responsavel_principal INTEGER NOT NULL DEFAULT 0 CHECK (eh_responsavel_principal IN (0, 1)),
    FOREIGN KEY (id_investigacao) REFERENCES INVESTIGACAO(id_investigacao) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (id_detetive) REFERENCES DETETIVE(id_detetive) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE MISSAO (
    id_missao INTEGER PRIMARY KEY AUTOINCREMENT,
    id_investigacao INTEGER NOT NULL,
    titulo TEXT NOT NULL,
    descricao TEXT NOT NULL,
    data_inicio TEXT NOT NULL,
    data_fim TEXT,
    status TEXT NOT NULL DEFAULT 'PLANEJADA' CHECK (status IN ('PLANEJADA', 'EM_ANDAMENTO', 'CONCLUIDA', 'CANCELADA')),
    FOREIGN KEY (id_investigacao) REFERENCES INVESTIGACAO(id_investigacao) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE MISSAO_DETETIVE (
    id_missao INTEGER NOT NULL,
    id_detetive INTEGER NOT NULL,
    PRIMARY KEY (id_missao, id_detetive),
    FOREIGN KEY (id_missao) REFERENCES MISSAO(id_missao) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (id_detetive) REFERENCES DETETIVE(id_detetive) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE UTILIZACAO_EQUIPAMENTO (
    id_utilizacao INTEGER PRIMARY KEY AUTOINCREMENT,
    id_equipamento INTEGER NOT NULL,
    id_missao INTEGER NOT NULL,
    id_detetive INTEGER NOT NULL,
    data_inicio TEXT NOT NULL,
    data_fim TEXT,
    FOREIGN KEY (id_equipamento) REFERENCES EQUIPAMENTO(id_equipamento) ON DELETE RESTRICT ON UPDATE CASCADE,
    FOREIGN KEY (id_missao) REFERENCES MISSAO(id_missao) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (id_detetive) REFERENCES DETETIVE(id_detetive) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE PESSOA (
    id_pessoa INTEGER PRIMARY KEY AUTOINCREMENT,
    nome TEXT NOT NULL,
    cpf TEXT UNIQUE,
    descricao_fisica TEXT,
    observacoes TEXT
);

CREATE TABLE ENVOLVIMENTO (
    id_envolvimento INTEGER PRIMARY KEY AUTOINCREMENT,
    id_investigacao INTEGER NOT NULL,
    id_pessoa INTEGER NOT NULL,
    papel TEXT NOT NULL CHECK (papel IN ('SUSPEITO', 'VITIMA', 'TESTEMUNHA', 'PESSOA_PROCURADA', 'PESSOA_DE_INTERESSE')),
    data_registro TEXT NOT NULL DEFAULT (DATE('now')),
    FOREIGN KEY (id_investigacao) REFERENCES INVESTIGACAO(id_investigacao) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (id_pessoa) REFERENCES PESSOA(id_pessoa) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE ENTREVISTA (
    id_entrevista INTEGER PRIMARY KEY AUTOINCREMENT,
    id_investigacao INTEGER NOT NULL,
    id_pessoa INTEGER NOT NULL,
    data_hora TEXT NOT NULL,
    transcricao_resumo TEXT NOT NULL,
    FOREIGN KEY (id_investigacao) REFERENCES INVESTIGACAO(id_investigacao) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (id_pessoa) REFERENCES PESSOA(id_pessoa) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE ENTREVISTA_DETETIVE (
    id_entrevista INTEGER NOT NULL,
    id_detetive INTEGER NOT NULL,
    PRIMARY KEY (id_entrevista, id_detetive),
    FOREIGN KEY (id_entrevista) REFERENCES ENTREVISTA(id_entrevista) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (id_detetive) REFERENCES DETETIVE(id_detetive) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE EVIDENCIA (
    id_evidencia INTEGER PRIMARY KEY AUTOINCREMENT,
    id_investigacao INTEGER NOT NULL,
    id_detetive_coletor INTEGER NOT NULL,
    tipo TEXT NOT NULL,
    descricao TEXT NOT NULL,
    data_coleta TEXT NOT NULL,
    origem TEXT NOT NULL,
    FOREIGN KEY (id_investigacao) REFERENCES INVESTIGACAO(id_investigacao) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (id_detetive_coletor) REFERENCES DETETIVE(id_detetive) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE EVIDENCIA_PESSOA (
    id_evidencia INTEGER NOT NULL,
    id_pessoa INTEGER NOT NULL,
    PRIMARY KEY (id_evidencia, id_pessoa),
    FOREIGN KEY (id_evidencia) REFERENCES EVIDENCIA(id_evidencia) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (id_pessoa) REFERENCES PESSOA(id_pessoa) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE LOCAL (
    id_local INTEGER PRIMARY KEY AUTOINCREMENT,
    id_missao INTEGER,
    id_entrevista INTEGER,
    endereco_completo TEXT NOT NULL,
    cidade TEXT NOT NULL,
    estado TEXT NOT NULL,
    coordenadas_gps TEXT,
    FOREIGN KEY (id_missao) REFERENCES MISSAO(id_missao) ON DELETE SET NULL ON UPDATE CASCADE,
    FOREIGN KEY (id_entrevista) REFERENCES ENTREVISTA(id_entrevista) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TABLE EVIDENCIA_LOCAL (
    id_evidencia INTEGER NOT NULL,
    id_local INTEGER NOT NULL,
    PRIMARY KEY (id_evidencia, id_local),
    FOREIGN KEY (id_evidencia) REFERENCES EVIDENCIA(id_evidencia) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (id_local) REFERENCES LOCAL(id_local) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE RELATORIO (
    id_relatorio INTEGER PRIMARY KEY AUTOINCREMENT,
    id_investigacao INTEGER NOT NULL,
    id_autor INTEGER NOT NULL,
    titulo TEXT NOT NULL,
    conteudo TEXT NOT NULL,
    data_emissao TEXT NOT NULL DEFAULT (DATE('now')),
    tipo_relatorio TEXT NOT NULL CHECK (tipo_relatorio IN ('INTERMEDIARIO', 'FINAL')),
    FOREIGN KEY (id_investigacao) REFERENCES INVESTIGACAO(id_investigacao) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (id_autor) REFERENCES DETETIVE(id_detetive) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE CONTRATO (
    id_contrato INTEGER PRIMARY KEY AUTOINCREMENT,
    id_cliente INTEGER NOT NULL,
    id_investigacao INTEGER NOT NULL UNIQUE,
    numero_contrato TEXT NOT NULL UNIQUE,
    data_assinatura TEXT NOT NULL,
    valor_total REAL NOT NULL CHECK (valor_total > 0),
    termos TEXT NOT NULL,
    FOREIGN KEY (id_cliente) REFERENCES CLIENTE(id_cliente) ON DELETE RESTRICT ON UPDATE CASCADE,
    FOREIGN KEY (id_investigacao) REFERENCES INVESTIGACAO(id_investigacao) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE PAGAMENTO (
    id_pagamento INTEGER PRIMARY KEY AUTOINCREMENT,
    id_contrato INTEGER NOT NULL,
    data_pagamento TEXT NOT NULL,
    valor REAL NOT NULL CHECK (valor > 0),
    status TEXT NOT NULL DEFAULT 'PENDENTE' CHECK (status IN ('CONFIRMADO', 'PENDENTE', 'CANCELADO')),
    FOREIGN KEY (id_contrato) REFERENCES CONTRATO(id_contrato) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE HISTORICO (
    id_historico INTEGER PRIMARY KEY AUTOINCREMENT,
    id_investigacao INTEGER NOT NULL,
    data_hora TEXT NOT NULL DEFAULT (DATETIME('now')),
    acao_realizada TEXT NOT NULL,
    usuario_sistema TEXT NOT NULL,
    FOREIGN KEY (id_investigacao) REFERENCES INVESTIGACAO(id_investigacao) ON DELETE CASCADE ON UPDATE CASCADE
);